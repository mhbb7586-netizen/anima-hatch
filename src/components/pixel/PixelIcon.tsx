export function PixelIcon({ name, size = 24, className, color }: IconProps) {
  const draw = grids[name];
  if (!draw) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 10 10"
      shapeRendering="crispEdges"
      className={cn("inline-block shrink-0", className)}
      style={color ? { color } : undefined}
      aria-hidden
    >
      {draw(color ?? "currentColor")}
    </svg>
  );
}
